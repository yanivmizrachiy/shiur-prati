// tools/verify-question-coverage-deep.mjs
// Deep question-coverage census: boots the real engine stack and grades every
// question-producing engine id as STRONG / PARTIAL / NO_CLEAR_SOURCE against
// explicit criteria, then writes docs/reports/QUESTION_COVERAGE_CENSUS_LATEST.md.
//
// STRONG criteria (all must hold):
//   1. valid source metadata in the registry (sourceFile is one of the 10 PDFs)
//   2. >=3 of {open,mcq,tf,mistake} produce non-empty question+answer, no undefined/NaN
//   3. answer carries an explanation (answerHTML length >= 25)
//   4. basic / standard / challenge all produce output
//   5. visual present when the skill needs one (geometry, or chart/coordinate/graph)
// PASS gate: strong >= 12 AND noClearSource (among engine ids) == 0.
import fs from 'node:fs';
import { loadEngines } from './engine-load.mjs';

const { E, pilotIds, sourceFitIds, callEngine } = loadEngines();
const reg = E.SOURCE_REGISTRY || {};
const QTYPES = ['open', 'mcq', 'tf', 'mistake'];
const DIFFS = ['basic', 'standard', 'challenge'];
const SAMPLES = 14;
const BAD = /undefined|NaN/;

function needsVisual(meta) {
  if (!meta) return false;
  if (meta.domain === 'geometry') return true;
  return /chart|coordinate|graph|number_line|bar|pie/.test(meta.skill || '');
}

const rows = [];
const allIds = pilotIds.concat(sourceFitIds);
for (const id of allIds) {
  const meta = E.getSource(id);
  const qtypeOk = {}; let svgSeen = false, badSeen = false, answerRich = false, diffOk = {};
  for (const d of DIFFS) {
    for (const t of QTYPES) {
      let okThis = false;
      for (let i = 0; i < SAMPLES; i++) {
        let r; try { r = callEngine(id, d, t); } catch (e) { badSeen = true; continue; }
        if (!r || !r.questionHTML || !r.answerHTML) continue;
        const all = r.questionHTML + r.answerHTML;
        if (BAD.test(all)) { badSeen = true; continue; }
        okThis = true;
        diffOk[d] = true;
        if (/<svg|<table/.test(r.questionHTML)) svgSeen = true;
        if ((r.answerHTML || '').replace(/<[^>]+>/g, '').trim().length >= 25) answerRich = true;
      }
      if (okThis) qtypeOk[t] = true;
    }
  }
  const qtypeCount = Object.keys(qtypeOk).length;
  const diffCount = Object.keys(diffOk).length;
  const hasSource = !!(meta && E.validateSource(meta).ok);
  const visualOk = !needsVisual(meta) || svgSeen;
  let status;
  if (!hasSource) status = 'NO_CLEAR_SOURCE';
  else if (qtypeCount >= 3 && answerRich && diffCount === 3 && visualOk && !badSeen) status = 'STRONG';
  else status = 'PARTIAL';
  rows.push({ id, status, qtypeCount, hasSource, svgSeen, answerRich, diffCount, visualOk, badSeen,
    mcq: !!qtypeOk.mcq, tf: !!qtypeOk.tf, mistake: !!qtypeOk.mistake,
    sourceFile: meta ? meta.sourceFile : '-', skill: meta ? meta.skill : '-' });
}

const strong = rows.filter(r => r.status === 'STRONG');
const partial = rows.filter(r => r.status === 'PARTIAL');
const noClear = rows.filter(r => r.status === 'NO_CLEAR_SOURCE');
const fallbackLogical = Object.keys(reg).filter(k => reg[k].fallback).length;
const census = {
  engineIdsScanned: rows.length,
  strong: strong.length,
  partial: partial.length,
  noClearSource: noClear.length,
  withSvgOrVisual: rows.filter(r => r.svgSeen).length,
  withMcq: rows.filter(r => r.mcq).length,
  withTf: rows.filter(r => r.tf).length,
  withMistake: rows.filter(r => r.mistake).length,
  fallbackLogicalTopics: fallbackLogical,
  estimatedTemplateScore: rows.reduce((s, r) => s + r.qtypeCount * (r.svgSeen ? 2 : 1) * (r.diffCount), 0)
};

// ── write report ──
const domains = {};
for (const r of rows) {
  const d = (E.getSource(r.id) || {}).domain || 'other';
  (domains[d] = domains[d] || []).push(r);
}
let md = '# Question Coverage Census (deep)\n\n';
md += '_Generated by tools/verify-question-coverage-deep.mjs — ' + new Date().toISOString() + '_\n\n';
md += '## Summary\n\n```json\n' + JSON.stringify(census, null, 2) + '\n```\n\n';
md += '## STRONG engines (' + strong.length + ')\n\n| id | domain | source | skill | qtypes | visual |\n|---|---|---|---|---|---|\n';
for (const r of strong) md += `| ${r.id} | ${(E.getSource(r.id)||{}).domain||'-'} | ${r.sourceFile} | ${r.skill} | ${r.qtypeCount} | ${r.svgSeen ? 'yes' : '-'} |\n`;
md += '\n## PARTIAL engines (' + partial.length + ')\n\n| id | reason |\n|---|---|\n';
for (const r of partial) {
  const reasons = [];
  if (r.qtypeCount < 3) reasons.push('only ' + r.qtypeCount + ' qtypes');
  if (!r.answerRich) reasons.push('thin answers');
  if (r.diffCount < 3) reasons.push('only ' + r.diffCount + ' difficulties');
  if (!r.visualOk) reasons.push('missing required visual');
  if (r.badSeen) reasons.push('undefined/NaN seen');
  md += `| ${r.id} | ${reasons.join('; ') || 'n/a'} |\n`;
}
md += '\n## NO_CLEAR_SOURCE engines (' + noClear.length + ')\n\n' + (noClear.length ? noClear.map(r => '- ' + r.id).join('\n') : '_none_') + '\n';
fs.mkdirSync('docs/reports', { recursive: true });
fs.writeFileSync('docs/reports/QUESTION_COVERAGE_CENSUS_LATEST.md', md);

console.log(JSON.stringify(census, null, 2));
const domainsCovered = new Set(strong.map(r => (E.getSource(r.id) || {}).domain));
console.log('STRONG domains covered: ' + [...domainsCovered].sort().join(', '));

let fails = 0;
function check(n, ok, info) { console.log((ok ? 'PASS' : 'FAIL') + ' — ' + n + (ok ? '' : '  :: ' + info)); if (!ok) fails++; }
check('strong engines >= 12', census.strong >= 12, 'strong=' + census.strong);
check('no engine id without source metadata', census.noClearSource === 0, noClear.map(r => r.id).join(','));
check('STRONG spans >= 4 domains', domainsCovered.size >= 4, [...domainsCovered].join(','));
console.log(fails ? 'COVERAGE_DEEP_FAIL (' + fails + ')' : 'COVERAGE_DEEP_PASS');
process.exit(fails ? 1 : 0);
